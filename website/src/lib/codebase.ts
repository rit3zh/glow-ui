/**
 * Reads component source out of the `reacticx-codebase` R2 bucket.
 *
 * The bucket mirrors the library repo verbatim — `core/` is `src/components`,
 * `examples/` is `app/components`, `helpers/` is the shared utilities, and
 * `types/` is generated per component from its own type file — so the
 * docs show exactly what is in the repo rather than a snapshot that has to be
 * re-synced. `index.json` at the root lists every object, which is how a flat
 * component name resolves to a nested path.
 *
 * Everything here runs at build time, and the bucket is the only copy. The flat
 * per-kind directories that used to sit under the site root (`react-native/`,
 * `react-native-usage/`, `react-native-types/`) were a second copy of the same
 * files that had to be re-synced by hand, and are gone. A page whose object is
 * missing renders its own "not synced yet" note rather than failing the build.
 */

export const CODEBASE_ORIGIN = "https://pub-028ac77ff44d4123aed5b9b6592ec08d.r2.dev";

/** Bucket folder ← repo directory. Mirrors `cloudflare/codebase/config.ts`. */
export const CODEBASE_FOLDERS = {
  core: "core",
  examples: "examples",
  helpers: "helpers",
  /**
   * One `index.ts` per component, generated by `cloudflare/codebase/build-types.ts`
   * from whatever the component names its own type file. Resolving a slug to
   * its props is therefore the same shape as resolving one to its usage.
   */
  types: "types",
} as const;

interface IndexEntry {
  /** Path relative to the folder prefix, e.g. `base/button/index.tsx`. */
  path: string;
  /** Full object key, e.g. `core/base/button/index.tsx`. */
  key: string;
  size: number;
  hash: string;
  contentType: string;
}

interface CodebaseIndex {
  bucket: string;
  generatedAt: string;
  total: number;
  folders: Record<string, { prefix: string; source: string; files: IndexEntry[] }>;
}

const url = (key: string) =>
  `${CODEBASE_ORIGIN}/${key.split("/").map(encodeURIComponent).join("/")}`;

/**
 * Fetches one object, retrying the failures that are worth retrying.
 *
 * A build prerenders hundreds of pages across nine workers, all reading from
 * the same bucket, so r2.dev rate-limits it (HTTP 429). Without a retry those
 * pages render their "not synced yet" note instead of the source — and because
 * the App Router derives a page's prefetch segment tree from what it rendered,
 * two pages that disagree about the same file leave the `.segments` output on
 * disk inconsistent and the build dies later in `next build` or in the OpenNext
 * bundler. Retrying keeps a build's view of the bucket the same throughout.
 */
async function fetchWithRetry(key: string, attempts = 5): Promise<Response> {
  let lastError: Error | undefined;

  for (let attempt = 0; attempt < attempts; attempt++) {
    if (attempt > 0) {
      // Exponential backoff, jittered so the workers don't retry in lockstep.
      const backoff = 250 * 2 ** (attempt - 1);
      await new Promise((resolve) =>
        setTimeout(resolve, backoff + Math.random() * backoff),
      );
    }

    let response: Response;
    try {
      response = await fetch(url(key), { cache: "no-store" });
    } catch (error) {
      // Connection reset, DNS blip, socket timeout — all worth another go.
      lastError = error as Error;
      continue;
    }

    // 429 and 5xx are transient. Everything else — including 404, which means
    // the object genuinely is not in the bucket — is the answer.
    if (response.status !== 429 && response.status < 500) return response;

    lastError = new Error(`HTTP ${response.status}`);
  }

  throw lastError ?? new Error("request failed");
}

