/**
 * One fetch per build, shared by every page.
 *
 * A rejected promise is not memoised — a transient failure on the first page
 * would otherwise poison every later one.
 */
let indexPromise: Promise<CodebaseIndex | null> | null = null;

async function loadIndex(): Promise<CodebaseIndex | null> {
  indexPromise ??= (async () => {
    try {
      // Never cached across builds. This listing is the manifest of what the
      // bucket holds, so a persisted copy silently hides every component added
      // since — the page renders "not synced yet" for source that is right
      // there. One request per build, deduped in process by `indexPromise`.
      const response = await fetchWithRetry("index.json");
      if (!response.ok) throw new Error(`HTTP ${response.status}`);
      return (await response.json()) as CodebaseIndex;
    } catch (error) {
      console.warn(
        `[codebase] could not load index.json (${(error as Error).message}) — ` +
          "falling back to the synced copies on disk",
      );
      indexPromise = null;
      return null;
    }
  })();

  return indexPromise;
}

