const fileCache = new Map<string, Promise<string | null>>();

/** Fetches one object. Cached per key for the lifetime of the build. */
export function fetchCodebaseFile(key: string): Promise<string | null> {
  const cached = fileCache.get(key);
  if (cached) return cached;

  const pending = (async () => {
    try {
      // Same reasoning as the index: a component's source changes, and a
      // build that reuses last week's copy is worse than one that refetches.
      // `fileCache` keeps it to one request per key per build.
      const response = await fetchWithRetry(key);
      if (response.status === 404) return null;
      if (!response.ok) throw new Error(`HTTP ${response.status}`);
      return await response.text();
    } catch (error) {
      console.warn(`[codebase] could not read ${key}: ${(error as Error).message}`);
      // The miss stays memoised. Every page that reads this key has to agree on
      // what it holds — a key that reads null for one page and its source for
      // the next is what leaves the segment output inconsistent.
      return null;
    }
  })();

  fileCache.set(key, pending);
  return pending;
}

/**
 * The component's own directory inside the bucket folder, e.g. `base/button`.
 * Null when the component is not in the bucket.
 */
export async function resolveComponentDir(
  folder: keyof typeof CODEBASE_FOLDERS,
  component: string,
): Promise<string | null> {
  const lookup = await getLookup();
  return lookup?.get(folder)?.get(normalizeDirName(component))?.dir ?? null;
}

export interface ComponentFileRef {
  /** Path relative to the component's own folder, e.g. `internal/test.ts`. */
  path: string;
  /** Full object key in the bucket. */
  key: string;
  size: number;
}

/**
 * Every file in a component's folder, in the order a file tree should show it.
 *
 * The docs used to hand-list `index.tsx` and `types.ts`, which hid everything
 * else a component actually ships — `conf.ts`, `const.ts`, `utils.ts`, nested
 * `hooks/` and `types/` directories. The bucket mirrors the folder as it is, so
 * the tree can simply show it.
 */
export async function listComponentFiles(
  folder: keyof typeof CODEBASE_FOLDERS,
  component: string,
): Promise<ComponentFileRef[]> {
  const lookup = await getLookup();
  const found = lookup?.get(folder)?.get(normalizeDirName(component));
  if (!found) return [];

  const entryPoints = new Set(mainCandidates(component));

  return [...found.files.entries()]
    // A component folder can carry an image or a font next to its code; those
    // belong in the folder but not in a syntax-highlighted source tree.
    .filter(([path]) => CODE_FILE.test(path))
    .map(([path, entry]) => ({ path, key: entry.key, size: entry.size }))
    .sort((a, b) => {
      const depthA = a.path.includes("/");
      const depthB = b.path.includes("/");

      // Loose files before directories, so the entry point is never buried.
      if (depthA !== depthB) return depthA ? 1 : -1;

      // The component's own entry point leads.
      const entryA = entryPoints.has(a.path);
      const entryB = entryPoints.has(b.path);
      if (entryA !== entryB) return entryA ? -1 : 1;

      return a.path.localeCompare(b.path);
    });
}

/**
 * Every file under one directory of a bucket folder, in the same order
 * `listComponentFiles` returns a component's own.
 *
 * The lookup above resolves a component by name, which is what the component
 * docs have: a slug. The blocks catalogue has the path instead — each mockup
 * records the block it is a screenshot of — and a name lookup is the wrong tool
 * for it twice over. `air-bnb-v2` is not the `airbnb-v2` its screenshot is
 * called, and a block directory sits three levels deep, so a collision with a
 * shallower directory of the same name would silently win. An explicit path
 * has neither problem.
 */
export async function listFilesInDir(
  folder: keyof typeof CODEBASE_FOLDERS,
  dir: string,
): Promise<ComponentFileRef[]> {
  const index = await loadIndex();
  const files = index?.folders[folder]?.files;
  if (!files) return [];

  const prefix = `${dir.replace(/\/+$/, "")}/`;

  return files
    .filter((entry) => entry.path.startsWith(prefix))
    .map((entry) => ({
      path: entry.path.slice(prefix.length),
      key: entry.key,
      size: entry.size,
    }))
    // Nothing but code, and never a nested file above a loose one.
    .filter((ref) => CODE_FILE.test(ref.path))
    .sort((a, b) => {
      const nestedA = a.path.includes("/");
      const nestedB = b.path.includes("/");
      if (nestedA !== nestedB) return nestedA ? 1 : -1;

      // The entry point leads, whatever the folder is called.
      const entryA = a.path === "index.tsx" || a.path === "index.ts";
      const entryB = b.path === "index.tsx" || b.path === "index.ts";
      if (entryA !== entryB) return entryA ? -1 : 1;

      return a.path.localeCompare(b.path);
    });
}

/**
 * One file of a component, read from the bucket.
 *
 * Null when the component is not in the index or the object is not there —
 * a sync gap, which the caller shows as a note instead of a broken page.
 */
export async function readComponentFile(
  folder: keyof typeof CODEBASE_FOLDERS,
  component: string,
  fileName: string,
): Promise<string | null> {
  const key = await resolveCodebaseKey(folder, component, fileName);
  return key ? await fetchCodebaseFile(key) : null;
}
