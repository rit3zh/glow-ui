/** `search-bar` -> `SearchBar`, matching how the repo names its main files. */
function toPascalCase(name: string) {
  return name
    .split("-")
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join("");
}

/**
 * The file names a component's entry point goes by, most canonical first.
 *
 * The repo is not uniform here — most folders use `index.tsx`, some re-export
 * from `index.ts`, and a few name the file after the component
 * (`SearchBar.tsx`, `FloatingSheet.tsx`). The flat sync resolved the same list,
 * so this keeps the docs showing the same file it used to.
 */
function mainCandidates(component: string) {
  const pascal = toPascalCase(component);
  return ["index.tsx", "index.ts", `${pascal}.tsx`, `${component}.tsx`];
}

/** Likewise for the types file that sits next to it. */
function typesCandidates(component: string) {
  const pascal = toPascalCase(component);
  return [
    "types.ts",
    `${pascal}.types.ts`,
    `${pascal}.props.ts`,
    "types/index.ts",
    "types.tsx",
  ];
}

/** The candidate list for a file the docs asks for by its canonical name. */
function candidatesFor(fileName: string, component: string) {
  if (fileName === "index.tsx") return mainCandidates(component);
  if (fileName === "types.ts") return typesCandidates(component);
  return [fileName];
}

/**
 * `Toast` and `toast` are the same component; so are `FloatingSheet` and
 * `floating-sheet`.
 *
 * The repo names most component directories in kebab case but not all of them,
 * and the docs slug is always kebab. Matching on a normalised name is what lets
 * `/components/toast` find `molecules/Toast/` instead of falling back to a flat
 * two-file listing that hides most of what the component ships.
 */
function normalizeDirName(name: string) {
  return name
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1-$2")
    .replace(/[_\s]+/g, "-")
    .toLowerCase();
}

/** Files the source tree shows. Binaries in a component folder are skipped. */
const CODE_FILE = /\.(tsx?|jsx?|mjs|cjs|json|css|md|mdx)$/i;

interface ComponentFiles {
  /** Path of the component's own directory, relative to the folder prefix. */
  dir: string;
  /** Every file under it, keyed by path relative to `dir`. */
  files: Map<string, IndexEntry>;
}

type Lookup = Map<string, Map<string, ComponentFiles>>;

let lookupPromise: Promise<Lookup | null> | null = null;

/**
 * Builds `component name → its files` for each bucket folder.
 *
 * Every directory is a candidate, keyed by its normalised name, because a
 * component is not always a folder with an `index.tsx` in it —
 * `screens/empty-state/` holds only a `v1/` subfolder. Ranking settles the
 * collisions: a directory holding a plausible entry point beats one that does
 * not, and among equals the shallower path wins — the same tie-break the flat
 * sync used.
 */
function buildLookup(index: CodebaseIndex): Lookup {
  const lookup: Lookup = new Map();

  for (const [folder, { files }] of Object.entries(index.folders)) {
    // dir -> whether it directly holds an entry point.
    const directories = new Map<string, boolean>();

    for (const entry of files) {
      const segments = entry.path.split("/");
      const fileName = segments.pop()!;

      // Register the file's own directory and every ancestor of it.
      for (let depth = segments.length; depth > 0; depth -= 1) {
        const dir = segments.slice(0, depth).join("/");
        const isRoot =
          depth === segments.length &&
          mainCandidates(normalizeDirName(segments[depth - 1]!)).includes(fileName);

        directories.set(dir, (directories.get(dir) ?? false) || isRoot);
      }
    }

    const chosen = new Map<string, { dir: string; hasEntry: boolean }>();

    for (const [dir, hasEntry] of directories) {
      const name = normalizeDirName(dir.split("/").pop()!);
      const current = chosen.get(name);

      if (current) {
        if (current.hasEntry && !hasEntry) continue;
        if (current.hasEntry === hasEntry) {
          if (current.dir.split("/").length <= dir.split("/").length) continue;
        }
      }

      chosen.set(name, { dir, hasEntry });
    }

    const byComponent = new Map<string, ComponentFiles>();
    for (const [name, { dir }] of chosen) {
      byComponent.set(name, { dir, files: new Map() });
    }

    // Attach every file that lives under a component root, nested ones included.
    for (const entry of files) {
      for (const bucket of byComponent.values()) {
        if (!entry.path.startsWith(`${bucket.dir}/`)) continue;
        bucket.files.set(entry.path.slice(bucket.dir.length + 1), entry);
      }
    }

    lookup.set(folder, byComponent);
  }

  return lookup;
}

async function getLookup() {
  lookupPromise ??= (async () => {
    const index = await loadIndex();
    if (!index) {
      lookupPromise = null;
      return null;
    }
    return buildLookup(index);
  })();

  return lookupPromise;
}

/**
 * The object key for one file of a component, or null when it is not there.
 *
 * `fileName` is the canonical name the docs use — `index.tsx` and `types.ts`
 * expand to the candidate lists above, anything else is matched literally.
 */
export async function resolveCodebaseKey(
  folder: keyof typeof CODEBASE_FOLDERS,
  component: string,
  fileName: string,
): Promise<string | null> {
  const lookup = await getLookup();
  const found = lookup?.get(folder)?.get(normalizeDirName(component));
  if (!found) return null;

  for (const candidate of candidatesFor(fileName, component)) {
    const entry = found.files.get(candidate);
    if (entry) return entry.key;
  }

  return null;
}

